const fs = require("node:fs");
const path = require("node:path");

const FIREBASE_VERSION = "11.6.0";

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const vars = {};
  const content = fs.readFileSync(filePath, "utf8");
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

function resolveFirebaseConfig(appRoot) {
  const envFiles = [
    ".env",
    ".env.development",
    ".env.production",
    ".env.local",
    ".env.development.local",
    ".env.production.local",
  ];

  const merged = {};
  for (const file of envFiles) {
    Object.assign(merged, parseEnvFile(path.join(appRoot, file)));
  }
  Object.assign(merged, process.env);

  let apiKey = merged.NEXT_PUBLIC_FIREBASE_API_KEY;
  let authDomain = merged.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN;
  let projectId = merged.NEXT_PUBLIC_FIREBASE_PROJECT_ID;
  let messagingSenderId = merged.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID;
  let appId = merged.NEXT_PUBLIC_FIREBASE_APP_ID;

  if (!apiKey || !authDomain || !projectId || !messagingSenderId || !appId) {
    const utilityEnvPath = path.resolve(appRoot, "../../be/DragBizz-Utility/.env");
    const utilityEnv = parseEnvFile(utilityEnvPath);
    apiKey = apiKey || utilityEnv.FCM_API_KEY;
    authDomain = authDomain || utilityEnv.FCM_DOMAIN;
    projectId = projectId || utilityEnv.FCM_PROJECT_ID;
    messagingSenderId = messagingSenderId || utilityEnv.FCM_SENDER_ID;
    appId = appId || utilityEnv.FCM_APP_ID;
  }

  return { apiKey, authDomain, projectId, messagingSenderId, appId };
}

function generateFirebaseServiceWorker(appRoot) {
  const outFile = path.join(appRoot, "public", "firebase-messaging-sw.js");
  const config = resolveFirebaseConfig(appRoot);
  const missing = Object.entries(config)
    .filter(([, v]) => !v)
    .map(([k]) => k);

  if (missing.length > 0) {
    if (fs.existsSync(outFile)) {
      console.log(`[generate-firebase-sw] Using existing ${outFile}`);
      return;
    }
    console.warn(`[generate-firebase-sw] Skipped: missing ${missing.join(", ")}`);
    return;
  }

  const sw = `/* Auto-generated by scripts/generate-firebase-sw.cjs — do not edit manually */
importScripts("https://www.gstatic.com/firebasejs/${FIREBASE_VERSION}/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/${FIREBASE_VERSION}/firebase-messaging-compat.js");

firebase.initializeApp({
  apiKey: "${config.apiKey}",
  authDomain: "${config.authDomain}",
  projectId: "${config.projectId}",
  messagingSenderId: "${config.messagingSenderId}",
  appId: "${config.appId}",
});

const messaging = firebase.messaging();

function buildNotificationData(payload) {
  const data = { ...(payload.data || {}) };
  if (payload.notification?.title && !data.title) {
    data.title = payload.notification.title;
  }
  if (payload.notification?.body && !data.body) {
    data.body = payload.notification.body;
  }
  if (!data.url && payload.fcmOptions?.link) {
    data.url = payload.fcmOptions.link;
  }
  return data;
}

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || payload.data?.title || "Notification";
  const body = payload.notification?.body || payload.data?.body || "";
  const icon = payload.notification?.icon || payload.data?.icon || "/logo.png";
  const badge = payload.notification?.badge || payload.data?.badge;
  const data = buildNotificationData(payload);

  return self.registration.showNotification(title, {
    body,
    icon,
    badge,
    data,
  }).catch((error) => {
    console.error("[FCM] background showNotification failed", error);
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();

  const data = event.notification.data || {};
  const targetPath = data.url || data.click_action || "/dashboard";
  const targetUrl = targetPath.startsWith("http")
    ? targetPath
    : self.location.origin + (targetPath.startsWith("/") ? targetPath : "/" + targetPath);

  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if (client.url.startsWith(self.location.origin) && "focus" in client) {
          return client.focus();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(targetUrl);
      }
    })
  );
});
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, sw, "utf8");
  console.log(`[generate-firebase-sw] Wrote ${outFile}`);
}

module.exports = {
  generateFirebaseServiceWorker,
  resolveFirebaseConfig,
};

